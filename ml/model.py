def _build_pipeline() -> Pipeline:
    return Pipeline([
        ("tfidf", TfidfVectorizer(
            analyzer="word",
            ngram_range=(1, 2),
            max_features=5000,
            sublinear_tf=True,
        )),
        ("clf", LogisticRegression(
            max_iter=1000,
            C=1.0,
            class_weight="balanced",
            random_state=42,
        )),
    ])


def train_and_save() -> Tuple[Pipeline, float]:
    texts = [t for t, _ in TRAINING_DATA]
    labels = [l for _, l in TRAINING_DATA]

    X_train, X_test, y_train, y_test = train_test_split(
        texts, labels, test_size=0.2, random_state=42, stratify=labels
    )

    pipeline = _build_pipeline()
    pipeline.fit(X_train, y_train)

    acc = accuracy_score(y_test, pipeline.predict(X_test))
    os.makedirs(os.path.dirname(MODEL_PATH), exist_ok=True)
    joblib.dump(pipeline, MODEL_PATH)
    return pipeline, acc


def load_or_train() -> Pipeline:
    if os.path.exists(MODEL_PATH):
        return joblib.load(MODEL_PATH)
    pipeline, _ = train_and_save()
    return pipeline


_pipeline: Pipeline | None = None


def get_classifier() -> Pipeline:
    global _pipeline
    if _pipeline is None:
        _pipeline = load_or_train()
    return _pipeline


def classify_document(text: str) -> str:
    clf = get_classifier()
    return clf.predict([text])[0]


def classify_with_proba(text: str) -> dict:
    clf = get_classifier()
    label = clf.predict([text])[0]
    proba = clf.predict_proba([text])[0]
    classes = clf.classes_
    return {
        "predicted": label,
        "probabilities": {c: round(float(p), 3) for c, p in zip(classes, proba)},
    }
